def get_lang() -> str:
    lang = session.get("lang", DEFAULT_LANG)
    return lang if lang in SUPPORTED_LANGS else DEFAULT_LANG


def translate(key: str, lang: str | None = None, **kwargs) -> str:
    lang = lang or get_lang()
    table = MESSAGES.get(lang) or MESSAGES[DEFAULT_LANG]
    text = table.get(key) or MESSAGES[DEFAULT_LANG].get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, ValueError):
            return text
    return text


def t(key: str, **kwargs) -> str:
    return translate(key, **kwargs)


def flash_t(key: str, category: str = "message", **kwargs) -> None:
    from flask import flash

    flash(translate(key, **kwargs), category)


def js_translations(lang: str | None = None) -> dict:
    lang = lang or get_lang()
    return {k: translate(k, lang) for k in JS_KEYS}


def speech_lang_code(lang: str | None = None) -> str:
    """BCP-47 tag for Web Speech API."""
    lang = lang or get_lang()
    return {"si": "si-LK", "ta": "ta-LK", "en": "en-LK"}.get(lang, "en-LK")
